import { describe, expect, it } from "vitest";
import {
  compareDiagrams,
  generateDiagrams,
  type Diagram,
} from "../src/diagrams.js";
import { gitIn } from "../src/git.js";
import { tempDir, writeText } from "./support/workspace.js";

/** A diagram rendering a fixed block, whatever the repository holds. */
const diagram = (
  name: string,
  document: string,
  edge = "a --> b",
): Diagram => ({
  name,
  document,
  render: () =>
    Promise.resolve(
      `\`\`\`mermaid\nflowchart LR\n  %% diagram: ${name}\n  ${edge}\n\`\`\`\n`,
    ),
});

const open = (name: string) =>
  `<!-- diagram:${name} generated by pnpm diagrams:generate, never edit by hand -->`;
const close = (name: string) => `<!-- /diagram:${name} -->`;

/** The region the generator writes for `diagram(name, ..., edge)`. */
const region = (name: string, edge = "a --> b") =>
  `${open(name)}\n\n\`\`\`mermaid\nflowchart LR\n  %% diagram: ${name}\n  ${edge}\n\`\`\`\n\n${close(name)}`;

/** A git repository holding `files`, each at its `/`-separated path. */
async function repository(files: Record<string, string>): Promise<string> {
  const root = await tempDir("diagrams");
  await gitIn(root)(["init", "--quiet"]);
  for (const [path, text] of Object.entries(files)) {
    await writeText(root, path, text);
  }
  return root;
}

describe("generateDiagrams", () => {
  it("returns, for each document, the region of each of its diagrams, in a stable order", async () => {
    const root = await repository({});

    expect(
      await generateDiagrams(root, [
        diagram("second", "docs/b.md"),
        diagram("zeta", "README.md"),
        diagram("alpha", "README.md"),
      ]),
    ).toEqual([
      {
        document: "README.md",
        regions: [
          { name: "alpha", text: region("alpha") },
          { name: "zeta", text: region("zeta") },
        ],
      },
      {
        document: "docs/b.md",
        regions: [{ name: "second", text: region("second") }],
      },
    ]);
  });

  it("refuses a diagram whose block does not declare its name", async () => {
    const root = await repository({});
    const unnamed: Diagram = {
      name: "unnamed",
      document: "README.md",
      render: () => Promise.resolve("```mermaid\nflowchart LR\n```\n"),
    };

    await expect(generateDiagrams(root, [unnamed])).rejects.toThrow(
      "The diagram unnamed renders no `%% diagram: unnamed` line in its block.",
    );
  });
});

describe("compareDiagrams", () => {
  it("rewrites only the marked regions, the prose around them untouched", async () => {
    const before =
      "# Title\n\nProse before.\n\n" +
      `<!-- diagram:one -->\n${close("one")}\n\n` +
      "Prose between.\n\n" +
      `${region("two", "old --> edge")}\n\nProse after.\n`;
    const root = await repository({ "README.md": before });

    const result = await compareDiagrams(root, [
      diagram("one", "README.md"),
      diagram("two", "README.md"),
    ]);

    expect(result.files).toEqual(
      new Map([
        [
          "README.md",
          "# Title\n\nProse before.\n\n" +
            `${region("one")}\n\n` +
            "Prose between.\n\n" +
            `${region("two")}\n\nProse after.\n`,
        ],
      ]),
    );
    expect(result.problems).toEqual([
      {
        kind: "changed",
        message:
          "README.md: the region of the diagram one differs from what `pnpm diagrams:generate` writes.",
      },
      {
        kind: "changed",
        message:
          "README.md: the region of the diagram two differs from what `pnpm diagrams:generate` writes.",
      },
    ]);
    expect(result.regions).toBe(2);
  });

  it("finds nothing to do when every region is what the generator writes", async () => {
    const root = await repository({
      "README.md": `Intro.\n\n${region("one")}\n`,
    });

    expect(await compareDiagrams(root, [diagram("one", "README.md")])).toEqual({
      files: new Map(),
      problems: [],
      regions: 1,
    });
  });

  it("reports a known diagram with no region, and a region no diagram writes", async () => {
    const root = await repository({
      "README.md": "No region here.\n",
      "docs/other.md": `${region("gone")}\n`,
      "docs/elsewhere.md": `${region("one")}\n`,
    });

    expect(
      (await compareDiagrams(root, [diagram("one", "README.md")])).problems,
    ).toEqual([
      {
        kind: "missing",
        message:
          "README.md: no region for the diagram one. Add the lines `<!-- diagram:one -->` and `<!-- /diagram:one -->` where it belongs, then run `pnpm diagrams:generate`.",
      },
      {
        kind: "unknown",
        message:
          "docs/elsewhere.md: a region of the diagram one, which `pnpm diagrams:generate` writes in README.md only. Remove it, or move it there.",
      },
      {
        kind: "unknown",
        message:
          "docs/other.md: a region of the diagram gone, which no diagram of `pnpm diagrams:generate` writes. Remove it, or add the diagram to release/src/diagram-list.ts.",
      },
    ]);
  });

  it("reports a region that never closes, a close with no open, and a region twice", async () => {
    const root = await repository({
      "README.md":
        `${open("one")}\n\n${close("other")}\n\n` +
        `${region("two")}\n\n${region("two")}\n\n${close("stray")}\n`,
    });

    expect(
      (
        await compareDiagrams(root, [
          diagram("one", "README.md"),
          diagram("two", "README.md"),
        ])
      ).problems,
    ).toEqual([
      {
        kind: "malformed",
        message:
          "README.md:1: the region of the diagram one is not closed by `<!-- /diagram:one -->` before line 3. Fix its markers, then run `pnpm diagrams:generate`.",
      },
      {
        kind: "malformed",
        message:
          "README.md:15: a second region of the diagram two. Remove one, then run `pnpm diagrams:generate`.",
      },
      {
        kind: "malformed",
        message:
          "README.md:25: `<!-- /diagram:stray -->` closes no region. Fix its markers, then run `pnpm diagrams:generate`.",
      },
    ]);
  });

  it("ignores marker lines inside fenced code and files git ignores", async () => {
    const shown =
      "```md\n<!-- diagram:example -->\n<!-- /diagram:example -->\n```\n";
    const root = await repository({
      ".gitignore": "collected/\n",
      "README.md": `${shown}\n${region("one")}\n`,
      "collected/README.md": `${region("one", "stale --> copy")}\n`,
    });

    expect(await compareDiagrams(root, [diagram("one", "README.md")])).toEqual({
      files: new Map(),
      problems: [],
      regions: 1,
    });
  });

  it("skips the Upstream skills the lock names, and reads the repository's own skills", async () => {
    const root = await repository({
      "skills-lock.json": JSON.stringify({
        version: 1,
        skills: { tdd: { source: "mattpocock/skills" } },
      }),
      "README.md": `${region("one")}\n`,
      ".claude/skills/tdd/SKILL.md": `${region("one", "upstream --> text")}\n`,
      ".claude/skills/add-wrapper/SKILL.md": `${region("one")}\n`,
    });

    expect(
      (await compareDiagrams(root, [diagram("one", "README.md")])).problems,
    ).toEqual([
      {
        kind: "unknown",
        message:
          ".claude/skills/add-wrapper/SKILL.md: a region of the diagram one, which `pnpm diagrams:generate` writes in README.md only. Remove it, or move it there.",
      },
    ]);
  });
});
