// The collected pages under the site's Markdown compiler (#670): each page
// docs:collect writes compiles as the build compiles it, through
// Docusaurus' MDX loader under the site's validated `markdown` config, and
// as plain Markdown, the way GitHub renders its source: an HTML comment (the
// marker of a generated region) is a comment, `<` and `{` are text, and a
// `mermaid` block is the theme's Mermaid component. `pnpm check` builds no
// site, so this is where a page the build would reject fails first.
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateConfig } from "@docusaurus/core/lib/server/configValidation.js";
import mdxLoader, { type Options } from "@docusaurus/mdx-loader";
import { afterEach, describe, expect, it } from "vitest";
import { siteConfig } from "../../config";
import { WORKSPACE } from "../../scripts/collect.mts";
import { collect } from "../../scripts/collector.mts";
import { fixture, GLOSSARY, REPOSITORY_FILES } from "../support/workspace.mts";

const SITE = dirname(dirname(dirname(fileURLToPath(import.meta.url))));

/** The loader's options, as the docs plugin gives them, under `docs:check`. */
const OPTIONS: Options = {
  markdownConfig: validateConfig(
    siteConfig({ strict: true }),
    "docusaurus.check.config.ts",
  ).markdown,
  admonitions: true,
  staticDirs: [],
  siteDir: SITE,
};

/** The compiled JavaScript of the page at `filePath`, as a build gets it. */
function compile(filePath: string, fileContent: string): Promise<string> {
  return new Promise((resolve, reject) => {
    const context = {
      _compiler: { name: "client" },
      resource: filePath,
      resourcePath: filePath,
      getOptions: () => OPTIONS,
      addDependency: () => undefined,
      async: () => (error: Error | null, result?: string) => {
        if (error) reject(error);
        else resolve(result ?? "");
      },
    };
    void mdxLoader.call(
      context as unknown as ThisParameterType<typeof mdxLoader>,
      fileContent,
    );
  });
}

let folders: string[] = [];

afterEach(async () => {
  await Promise.all(
    folders.map((folder) => rm(folder, { recursive: true, force: true })),
  );
  folders = [];
});

describe("the collected pages", () => {
  it("compile as plain Markdown, an HTML comment a comment, `<` and `{` text, a mermaid block the theme's component", async () => {
    const workspace = await fixture({
      ...REPOSITORY_FILES,
      "CONTEXT.md": `${GLOSSARY}
<!-- diagram:tiny generated by pnpm diagrams:generate, never edit by hand -->

\`\`\`mermaid
flowchart LR
  %% diagram: tiny
  a --> b
\`\`\`

<!-- /diagram:tiny -->

A Handle < its id, and {braces} stay text.
`,
    });
    folders.push(dirname(workspace.root));
    await collect(workspace);
    const path = join(workspace.docs, "contributing/glossary.md");

    const code = await compile(path, await readFile(path, "utf8"));

    expect(code).toMatch(
      /\bmermaid\s*,\s*\{\s*value:\s*"flowchart LR\\n {2}%% diagram: tiny\\n {2}a --> b"/,
    );
    expect(code).toContain("A Handle < its id, and {braces} stay text.");
  });

  it("of this repository each compile", async () => {
    const docs = await mkdtemp(join(tmpdir(), "reforged-website-pages-"));
    folders.push(docs);
    const report = await collect({ ...WORKSPACE, docs });
    const pages = report.collected
      .flatMap(({ paths }) => paths)
      .filter((path) => path.endsWith(".md"));
    expect(pages).toContain("contributing/guide.md");

    const failed: string[] = [];
    for (const page of pages) {
      const path = join(docs, page);
      await compile(path, await readFile(path, "utf8")).catch(
        (error: unknown) => {
          failed.push(`${page}: ${String(error)}`);
        },
      );
    }
    expect(failed).toEqual([]);
  });
});
