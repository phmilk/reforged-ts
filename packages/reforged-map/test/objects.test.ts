describe("the warnings", () => {
  it("warns of a TRIGSTR war3map.wts lacks, and treats the name as unset", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo", "TRIGSTR_009")], buildWts({})),
      WITH_BUILTINS,
    );

    expect(output.warnings).toEqual([
      "war3map.w3u: the name of h000 is TRIGSTR_009, which war3map.wts does not hold; h000 is named as if it set none.",
    ]);
    expect(constantsOf(customUnits(output))).toEqual(["Footman_h000"]);
  });

  it("warns of a file of an unknown format version, and reads the others", () => {
    const output = generateObjects(
      mapFolder({
        "war3map.w3u": buildObjectData({
          version: 9,
          custom: [customUnit("h000", "hfoo", "Old")],
        }),
        "war3mapSkin.w3u": buildObjectData({
          custom: [customUnit("h001", "hfoo", "Captain")],
        }),
      }),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([
      "war3map.w3u not read (unknown format version 9): its objects are left out. Save the map with the World Editor of 3.0.",
    ]);
    expect(constantsOf(customUnits(output))).toEqual(["Captain_h001"]);
  });

  it("warns of a truncated file, drops its objects, and reads the others", () => {
    const bytes = buildObjectData({
      custom: [customUnit("h000", "hfoo", "Captain")],
    });
    const output = generateObjects(
      mapFolder({
        "war3map.w3u": bytes.subarray(0, bytes.length - 3),
        "war3mapSkin.w3u": buildObjectData({
          custom: [customUnit("h001", "hfoo", "Guard")],
        }),
      }),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([
      "war3map.w3u not read (truncated): its objects are left out. Save the map with the World Editor of 3.0.",
    ]);
    expect(constantsOf(customUnits(output))).toEqual(["Guard_h001"]);
  });

  it("skips a file with an object of more than one set, with a warning", () => {
    const output = generateObjects(
      unitsMap([
        {
          original: "hfoo",
          custom: "h000",
          sets: [
            { flag: 0, modifications: [{ field: "unam", value: "A" }] },
            { flag: 1, modifications: [{ field: "unam", value: "B" }] },
          ],
        },
      ]),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([
      "war3map.w3u not read (h000 has 2 sets, whose layout is not settled, #460): its objects are left out. Save the map with the World Editor of 3.0.",
    ]);
    expect(constantsOf(customUnits(output))).toEqual([]);
  });

  it("keeps the first of a Custom Rawcode defined twice, with a warning", () => {
    const output = generateObjects(
      unitsMap([
        customUnit("h000", "hfoo", "First"),
        customUnit("h000", "hkni", "Second"),
      ]),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([
      "war3map.w3u defines the Custom unit h000 twice: the first definition is kept.",
    ]);
    expect(constantsOf(customUnits(output))).toEqual(["First_h000"]);
  });

  it("gives an overload and no constant to a Rawcode that cannot end an identifier, with a warning", () => {
    const output = generateObjects(
      unitsMap([customUnit("h-0 ", "hfoo", "Captain")]),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([
      'The Custom unit "h-0 " has no constant: its Rawcode cannot end an identifier. Name it with FourCC("h-0 "), or give it a Rawcode of letters and digits in the World Editor.',
    ]);
    expect(overloadedOf(overloads(output))).toEqual(["h-0 "]);
    expect(overloads(output)).not.toContain("Its constant");
    expect(constantsOf(customUnits(output))).toEqual([]);
  });
});

