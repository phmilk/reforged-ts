// The objects entry point over a map folder (#583): the Custom units of
// war3map.w3u and war3mapSkin.w3u, named through war3map.wts, to their
// FourCC overloads and their CustomUnits constants.

import fs from "node:fs";
import path from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import {
  CONSTANTS_FILES,
  MapFolderError,
  OBJECTS_DECLARATIONS_FILE,
  generateObjects,
  type ObjectsOutput,
} from "../src/index.js";
import {
  PACKAGE_ROOT,
  fixtureMap,
  makeTempDir,
  mapFolder,
  removeTemporary,
} from "./support/map-folder.js";
import {
  buildObjectData,
  buildWts,
  type TestObject,
} from "./support/object-data.js";

afterAll(removeTemporary);

const BANNER = [
  "// Generated by reforged-map from the map folder's Object data on every install, build and watch.",
  "// Do not edit: create and rename the objects in the World Editor.",
];

/** Options that resolve the workspace's reforged-builtins, as a Map project that installs it. */
const WITH_BUILTINS = { projectRoot: PACKAGE_ROOT };
/** Options that resolve no reforged-builtins. */
const withoutBuiltins = () => ({ projectRoot: makeTempDir() });

const NO_BUILTINS_WARNING =
  "reforged-builtins is not installed: a Custom object that keeps its base's name is named Unnamed. Install reforged-builtins to name it after its base.";

/** A Custom unit `custom` derived from `original`, named `name`, or keeping its base's name when `name` is left out. */
function customUnit(
  custom: string,
  original: string,
  name?: string,
): TestObject {
  return {
    original,
    custom,
    modifications: name === undefined ? [] : [{ field: "unam", value: name }],
  };
}

/** A map folder holding war3map.w3u (and war3map.wts when given) with these Custom units. */
function unitsMap(units: TestObject[], wts?: string): string {
  return mapFolder({
    "war3map.w3u": buildObjectData({ custom: units }),
    ...(wts !== undefined && { "war3map.wts": wts }),
  });
}

function file(output: ObjectsOutput, name: string): string {
  const found = output.files.find((f) => f.name === name);
  if (found === undefined) throw new Error(`no ${name}`);
  return found.contents;
}

const overloads = (output: ObjectsOutput) =>
  file(output, OBJECTS_DECLARATIONS_FILE);
const customUnits = (output: ObjectsOutput) =>
  file(output, CONSTANTS_FILES.unit);

/** The constants a constants module's object holds, in order. */
const constantsOf = (text: string): string[] =>
  [...text.matchAll(/^ {2}(\w+): -?\d+ as Rawcode</gm)].map((m) => m[1]);

/** The Rawcodes the overloads file gives an overload, in order. */
const overloadedOf = (text: string): string[] =>
  [...text.matchAll(/^declare function FourCC\(id: (".*?")\)/gm)].map(
    (m) => JSON.parse(m[1]) as string,
  );

const CONSTANTS_MODULES: [string, string][] = [
  ["unit", "custom-units.ts"],
  ["item", "custom-items.ts"],
  ["ability", "custom-abilities.ts"],
  ["buff", "custom-buffs.ts"],
  ["destructable", "custom-destructables.ts"],
  ["doodad", "custom-doodads.ts"],
  ["upgrade", "custom-upgrades.ts"],
];

describe("generateObjects", () => {
  it("writes the overload and the constant of a Custom unit named in the Skin file through a TRIGSTR, with their TSDoc", () => {
    const folder = mapFolder({
      "war3map.w3u": buildObjectData({ custom: [customUnit("h000", "hfoo")] }),
      "war3mapSkin.w3u": buildObjectData({
        custom: [customUnit("h000", "hfoo", "TRIGSTR_007")],
      }),
      "war3map.wts": buildWts({ 7: "Captain" }),
    });

    const output = generateObjects(folder, WITH_BUILTINS);

    expect(output.warnings).toEqual([]);
    expect(overloads(output)).toBe(
      [
        "/** @noSelfInFile */",
        ...BANNER,
        "",
        "/**",
        " * Captain (`h000`), a Custom unit of this map, derived from Footman (`hfoo`).",
        " *",
        " * Its constant is `CustomUnits.Captain_h000`, from the generated `custom-units.ts`.",
        " */",
        'declare function FourCC(id: "h000"): Rawcode<"unit">;',
        "",
      ].join("\n"),
    );
    expect(customUnits(output)).toBe(
      [
        ...BANNER,
        "// Each value is the integer FourCC returns for the Rawcode: its four bytes, big-endian.",
        "",
        "/**",
        " * The Custom units of this map, each named by its name and Rawcode.",
        " */",
        "export const CustomUnits = {",
        "  /**",
        "   * Captain (`h000`), a Custom unit of this map, derived from Footman (`hfoo`).",
        "   */",
        '  Captain_h000: 1747988528 as Rawcode<"unit">,',
        "} as const;",
        "",
      ].join("\n"),
    );
  });

  it("writes the declarations, then the seven constants modules, under the exported names", () => {
    const output = generateObjects(mapFolder({}), withoutBuiltins());

    expect(OBJECTS_DECLARATIONS_FILE).toBe("map-objects.d.ts");
    expect(Object.entries(CONSTANTS_FILES)).toEqual(CONSTANTS_MODULES);
    expect(output.files.map((f) => f.name)).toEqual([
      "map-objects.d.ts",
      ...CONSTANTS_MODULES.map(([, name]) => name),
    ]);
  });

  it("writes the seven constants modules empty and no overload, with no warning, for a map folder without Object data", () => {
    const output = generateObjects(mapFolder({}), withoutBuiltins());

    expect(output.warnings).toEqual([]);
    expect(overloadedOf(overloads(output))).toEqual([]);
    expect(overloads(output)).toBe(
      ["/** @noSelfInFile */", ...BANNER, ""].join("\n"),
    );
    expect(file(output, CONSTANTS_FILES.upgrade)).toContain(
      "export const CustomUpgrades = {} as const;",
    );
    for (const [kind, name] of Object.entries(CONSTANTS_FILES)) {
      expect(constantsOf(file(output, name)), kind).toEqual([]);
    }
  });

  it("throws a MapFolderError for a missing map folder", () => {
    const missing = path.join(makeTempDir(), "missing.w3m");

    expect(() => generateObjects(missing)).toThrow(MapFolderError);
    expect(() => generateObjects(missing)).toThrow(
      `Map folder not found: ${missing}.`,
    );
  });

  it("does not need war3map.lua", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo", "Captain")]),
      withoutBuiltins(),
    );

    expect(constantsOf(customUnits(output))).toEqual(["Captain_h000"]);
  });
});

describe("the name of a Custom unit", () => {
  it("names a Custom unit that keeps its base's name after its base", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo")]),
      WITH_BUILTINS,
    );

    expect(output.warnings).toEqual([]);
    expect(customUnits(output)).toContain(
      "   * Footman (`h000`), a Custom unit of this map, derived from Footman (`hfoo`).\n" +
        "   */\n" +
        '  Footman_h000: 1747988528 as Rawcode<"unit">,',
    );
  });

  it("names it Unnamed without reforged-builtins, with one warning, and its base by its Rawcode", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo"), customUnit("h001", "hkni")]),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([NO_BUILTINS_WARNING]);
    expect(constantsOf(customUnits(output))).toEqual([
      "Unnamed_h000",
      "Unnamed_h001",
    ]);
    expect(overloads(output)).toContain(
      " * Unnamed (`h000`), a Custom unit of this map, derived from `hfoo`.\n",
    );
  });

  it("gives no warning without reforged-builtins when every Custom unit sets its name", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo", "Captain")]),
      withoutBuiltins(),
    );

    expect(output.warnings).toEqual([]);
    expect(overloads(output)).toContain("derived from `hfoo`.");
  });

  it.each(
    JSON.parse(
      fs.readFileSync(
        path.join(
          PACKAGE_ROOT,
          "..",
          "..",
          "test",
          "fixtures",
          "constant-names.json",
        ),
        "utf8",
      ),
    ) as { name: string | null; rawcode: string; constant: string }[],
  )(
    "names $name $rawcode as $constant, by the table reforged-builtins' tests run",
    ({ name, rawcode, constant }) => {
      const output = generateObjects(
        unitsMap([customUnit(rawcode, "hfoo", name ?? undefined)]),
        withoutBuiltins(),
      );

      expect(constantsOf(customUnits(output))).toEqual([constant]);
    },
  );

  it("gives two Custom units of one name two constants, told apart by their Rawcodes", () => {
    const output = generateObjects(
      unitsMap([
        customUnit("h001", "hfoo", "Captain"),
        customUnit("h000", "hkni", "Captain"),
      ]),
      withoutBuiltins(),
    );

    expect(constantsOf(customUnits(output))).toEqual([
      "Captain_h000",
      "Captain_h001",
    ]);
    expect(overloadedOf(overloads(output))).toEqual(["h000", "h001"]);
  });

  it("names a Custom unit whose name is empty after its base", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo", "|cffff0000|r")]),
      WITH_BUILTINS,
    );

    expect(constantsOf(customUnits(output))).toEqual(["Footman_h000"]);
  });

  it("removes colour codes and line breaks from the name", () => {
    const output = generateObjects(
      unitsMap([customUnit("h000", "hfoo", "|cffff0000Royal|r|nGuard")]),
      withoutBuiltins(),
    );

    expect(overloads(output)).toContain(
      " * Royal Guard (`h000`), a Custom unit of this map",
    );
    expect(constantsOf(customUnits(output))).toEqual(["RoyalGuard_h000"]);
  });

  it("reads a literal name from the base file, and the Skin file's name over the base file's", () => {
    const output = generateObjects(
      mapFolder({
        "war3map.w3u": buildObjectData({
          custom: [
            customUnit("h000", "hfoo", "Base Name"),
            customUnit("h001", "hfoo", "Literal"),
          ],
        }),
        "war3mapSkin.w3u": buildObjectData({
          custom: [
            customUnit("h000", "hfoo", "TRIGSTR_1"),
            customUnit("h001", "hfoo"),
          ],
        }),
        "war3map.wts": buildWts({ 1: "Skin Name" }),
      }),
      withoutBuiltins(),
    );

    expect(constantsOf(customUnits(output))).toEqual([
      "SkinName_h000",
      "Literal_h001",
    ]);
  });

  it("reads a Custom unit the Skin file alone holds, and ignores a Skin entry with no modification", () => {
    const output = generateObjects(
      mapFolder({
        "war3mapSkin.w3u": buildObjectData({
          custom: [
            customUnit("h000", "hfoo", "Captain"),
            customUnit("h001", "hfoo"),
          ],
        }),
      }),
      withoutBuiltins(),
    );

    expect(constantsOf(customUnits(output))).toEqual(["Captain_h000"]);
  });

  it.each([
    ["a byte order mark and CRLF", { bom: true, crlf: true }],
    ["a comment line", { comments: true }],
  ])("reads war3map.wts with %s", (_, layout) => {
    const output = generateObjects(
      unitsMap(
        [customUnit("h000", "hfoo", "TRIGSTR_012")],
        buildWts({ 3: "Other", 12: "Captain" }, layout),
      ),
      withoutBuiltins(),
    );

    expect(constantsOf(customUnits(output))).toEqual(["Captain_h000"]);
  });

  it("takes the kind from the file, whatever the Rawcode's shape", () => {
    const output = generateObjects(
      unitsMap([customUnit("A000", "hfoo", "Captain")]),
      withoutBuiltins(),
    );

    expect(overloads(output)).toContain(
      'declare function FourCC(id: "A000"): Rawcode<"unit">;',
    );
    expect(constantsOf(customUnits(output))).toEqual(["Captain_A000"]);
  });
});

