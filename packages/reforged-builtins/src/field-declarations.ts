/**
 * The declarations of a field table of format 2 (#702): per Object kind, an
 * interface of its fields keyed by field id, each typed by its category,
 * with its TSDoc. `reforged-map/objects` types Object definitions from them
 * through the `reforged-builtins/fields` entry. Nothing here reads the
 * game: the check emits them again from the committed table and compares.
 */
import {
  CHECK_COMMAND,
  docComment,
  escape,
  list,
  PACKAGE_NAME,
  REGENERATE_COMMAND,
} from "./emit.js";
import {
  FIELD_KINDS,
  fieldsPath,
  type FieldEntry,
  type FieldTable,
} from "./fields.js";
import { byCodePoint, type ObjectKind } from "./model.js";

/** The declarations' path in the package: `3.0.1/fields.d.ts`. */
export const fieldDeclarationsPath = (gameVersion: string): string =>
  `${gameVersion}/fields.d.ts`;

/** The entry point of the newest Game version's declarations. */
export const FIELDS_ENTRY = "fields";

/** Each kind's interface and the extension of its Object data files. */
const KIND_FIELDS: Readonly<
  Record<ObjectKind, { name: string; plural: string; extension: string }>
> = {
  unit: { name: "UnitFields", plural: "units", extension: "w3u" },
  item: { name: "ItemFields", plural: "items", extension: "w3t" },
  ability: { name: "AbilityFields", plural: "abilities", extension: "w3a" },
  buff: { name: "BuffFields", plural: "buffs", extension: "w3h" },
  destructable: {
    name: "DestructableFields",
    plural: "destructables",
    extension: "w3b",
  },
  doodad: { name: "DoodadFields", plural: "doodads", extension: "w3d" },
  upgrade: { name: "UpgradeFields", plural: "upgrades", extension: "w3q" },
};

/** Whether a table has the facts the declarations need: format 2. */
export function hasDeclarations(table: FieldTable): boolean {
  return table.format === 2;
}

/** The declarations of a field table of format 2. */
export function emitFieldDeclarations(table: FieldTable): string {
  const { gameVersion } = table;
  const lines = [
    `// Generated by ${PACKAGE_NAME} from the field table of Game version ${gameVersion} (${fieldsPath(gameVersion)}).`,
    "// Derived identifiers only: field ids, metadata names and types, enUS labels and the raw values of enumerations.",
    "// Not affiliated with or endorsed by Blizzard Entertainment. Warcraft is a trademark of Blizzard Entertainment.",
    "// The field ids and labels are derived from the game's data and are not licensed by this package.",
    `// Never edited by hand: \`${REGENERATE_COMMAND}\` writes it and \`${CHECK_COMMAND}\` compares it.`,
    "",
    ...docComment("", [
      `The fields of each Object kind of Patch ${gameVersion}, by field id, as Object definitions set them. Each field gives its category, the type of one \`value\`, whether it holds a value per level and whether it is localizable.`,
    ]),
    "export interface Fields {",
    ...FIELD_KINDS.map(
      (kind) => `  readonly ${kind}: ${KIND_FIELDS[kind].name};`,
    ),
    "}",
  ];
  for (const kind of FIELD_KINDS) {
    const { name, plural } = KIND_FIELDS[kind];
    lines.push(
      "",
      ...docComment("", [
        `The fields of the ${plural} of Patch ${gameVersion}, by field id.`,
      ]),
      `export interface ${name} {`,
    );
    Object.keys(table.fields[kind])
      .sort(byCodePoint)
      .forEach((id, i) => {
        const entry = table.fields[kind][id];
        if (i > 0) lines.push("");
        lines.push(
          ...docComment("  ", describeField(table, kind, id, entry)),
          `  readonly ${propertyName(id)}: { readonly category: ${JSON.stringify(entry.category)}; readonly value: ${valueType(table, entry)}; readonly levels: ${String(entry.levels)}; readonly localizable: ${String(entry.localizable)} };`,
        );
      });
    lines.push("}");
  }
  return lines.join("\n") + "\n";
}

/**
 * A field's TSDoc: its enUS label and id, its metadata name and type, its
 * value type, its file, whether it has levels, and the bases it is
 * specific to.
 */
function describeField(
  table: FieldTable,
  kind: ObjectKind,
  id: string,
  entry: FieldEntry,
): string[] {
  const { plural, extension } = KIND_FIELDS[kind];
  const named =
    entry.label === undefined
      ? `\`${id}\`, unlabelled`
      : `${escape(entry.label)} (\`${id}\`)`;
  const file =
    entry.file === "skin"
      ? `the Skin file, war3mapSkin.${extension}`
      : `the base file, war3map.${extension}`;
  const levels = entry.levels
    ? kind === "doodad"
      ? "a value per variation"
      : "a value per level"
    : "one value";
  const lines = [
    `${named}, a field of the ${plural} of Patch ${table.gameVersion}.`,
    "",
    `Metadata name \`${escape(entry.field)}\`, metadata type \`${escape(entry.metaType ?? "")}\`, value type \`${entry.type}\`, in ${file}, ${levels}${entry.localizable ? ", localizable" : ""}.`,
  ];
  if (entry.specific !== undefined) {
    lines.push(
      "",
      `Specific to ${entry.specific.length === 1 ? "the base" : "the bases"} ${list(entry.specific.map((base) => `\`${escape(base)}\``))}.`,
    );
  }
  return lines;
}

/** The TypeScript type of one value of a field, by its category. */
function valueType(table: FieldTable, entry: FieldEntry): string {
  const values = table.enumerations?.[entry.metaType ?? ""];
  const union =
    values === undefined
      ? undefined
      : values.map((value) => JSON.stringify(value)).join(" | ");
  switch (entry.category) {
    case "boolean":
      return "boolean";
    case "text":
      return "string";
    case "enumeration":
      return union ?? "string";
    case "rawcode":
      return `Rawcode<${JSON.stringify(entry.of)}>`;
    case "rawcodeList":
      return `readonly Rawcode<${JSON.stringify(entry.of)}>[]`;
    case "stringList":
      return union === undefined
        ? "readonly string[]"
        : `readonly (${union})[]`;
    default:
      return "number";
  }
}

/** A field id as a property name: quoted unless it is an identifier. */
function propertyName(id: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id) ? id : JSON.stringify(id);
}
